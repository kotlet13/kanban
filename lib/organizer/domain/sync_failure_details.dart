String safeSyncFailureReason(String? reason) =>
    syncFailureSafeReasons.contains(reason) ? reason! : 'unknown';

class SyncFailureDetails {
  // Public named reason is sanitized by the getter; preserve const UI fixtures.
  const SyncFailureDetails({
    required this.stage,
    required this.occurredAt,
    required String reason,
    this.scopeId,
    // ignore: prefer_initializing_formals
  }) : _reason = reason;

  final SyncFailureStage stage;
  final DateTime? occurredAt;
  final String _reason;
  String get reason => safeSyncFailureReason(_reason);

  /// LOCAL DISPLAY ONLY. It is deliberately absent from diagnostic JSON.
  /// Null means an account issue; never substitute the current UI selection.
  final String? scopeId;

  Map<String, Object> toSafeDiagnosticJson() => {
    'stage': stage.name,
    'reason': reason,
    if (occurredAt != null) 'occurredAt': occurredAt!.toUtc().toIso8601String(),
  };
}

/// Explicit schema prevents accidental serialization of account/scope metadata.
/// Keep the most recent twenty items even when called with an unbounded list.
String syncFailureDiagnosticsJson(Iterable<SyncFailureDetails> failures) {
  final bounded = <SyncFailureDetails>[];
  for (final failure in failures) {
    bounded.add(failure);
    if (bounded.length > 20) bounded.removeAt(0);
  }
  return jsonEncode({
    'version': 1,
    'syncFailures': [
      for (final failure in bounded) failure.toSafeDiagnosticJson(),
    ],
  });
}
