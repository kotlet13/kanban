String safeHeldOperation(String value) =>
    heldDiagnosticOperations.contains(value) ? value : 'other';

class HeldCommandDiagnostic {
  const HeldCommandDiagnostic({
    required this.operation,
    this.receipt = HeldReceiptResult.notChecked,
    this.resume = HeldResumeResult.notAttempted,
    this.currentReason,
    this.retainedReason,
  });
  final String operation;
  final HeldReceiptResult receipt;
  final HeldResumeResult resume;
  final String? currentReason, retainedReason;
  Map<String, Object> toJson(String Function(String?) safeReason) => {
    'operation': safeHeldOperation(operation),
    'receipt': receipt.name,
    'resume': resume.name,
    if (currentReason != null) 'currentReason': safeReason(currentReason),
    if (retainedReason != null) 'retainedReason': safeReason(retainedReason),
  };
}

class HeldSyncDiagnostics {
  HeldSyncDiagnostics({
    required this.remaining,
    required Iterable<HeldCommandDiagnostic> samples,
  }) : samples = List.unmodifiable(samples.take(20));
  final int remaining;
  final List<HeldCommandDiagnostic> samples;
  Map<String, Object> toJson(String Function(String?) safeReason) => {
    'remaining': remaining < 0 ? 0 : remaining,
    'sampleLimit': 20,
    'samples': [for (final item in samples) item.toJson(safeReason)],
  };
}

/// Counts committed page applications, not unique records or complete domains.
/// A retry can apply the same record again. This is never a full-sync verdict.
class SyncTransferEvidence {
  const SyncTransferEvidence({
    required this.startedAt,
    this.contentPages = 0,
    this.contentRecords = 0,
    this.financePages = 0,
    this.financeRecords = 0,
  });
  final DateTime startedAt;
  final int contentPages, contentRecords, financePages, financeRecords;
  SyncTransferEvidence received({
    required bool finance,
    required int records,
  }) => SyncTransferEvidence(
    startedAt: startedAt,
    contentPages: contentPages + (finance ? 0 : 1),
    contentRecords: contentRecords + (finance ? 0 : records),
    financePages: financePages + (finance ? 1 : 0),
    financeRecords: financeRecords + (finance ? records : 0),
  );
  Map<String, Object> toJson() => {
    'startedAt': startedAt.toUtc().toIso8601String(),
    'committedContentPages': contentPages,
    'appliedContentRecords': contentRecords,
    'committedFinancePages': financePages,
    'appliedFinanceRecords': financeRecords,
    'countsAreUniqueRecords': false,
  };
}
